#!/usr/bin/env python3
"""Generate docs/rules/ from the rule catalog, rule docs and the precision audit.

    uv run python scripts/gen_rule_docs.py            # write docs/rules/
    uv run python scripts/gen_rule_docs.py --check    # exit 1 if docs/rules/ is stale

Everything on a page comes from code (``spaghetti.rules``, ``spaghetti.rule_docs``,
``spaghetti.config``) or from ``docs/precision.md``; the test suite runs ``--check``
so a rule cannot be added or retuned without its page following.
"""

from __future__ import annotations

import re
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
sys.path.insert(0, str(ROOT / "src"))

import spaghetti.config as _cfg  # noqa: E402
from spaghetti.rule_docs import RULE_DOCS  # noqa: E402
from spaghetti.rules import RULE_CATALOG, RuleMeta  # noqa: E402
from spaghetti.settings import threshold_names  # noqa: E402

DOCS = ROOT / "docs" / "rules"
PRECISION = ROOT / "docs" / "precision.md"
_ROW = re.compile(
    r"^\| `([a-z-]+)` \| (\d+) \| (\d+) \| (\d+) \| (\d+) \| (\d+) \| (\d+%) \| (\d+%) \| (\d+) \|$"
)


def precision_table() -> dict[str, dict[str, str]]:
    """Rule → {sampled, strict, lenient} from the Phase 1 per-rule table."""
    out: dict[str, dict[str, str]] = {}
    for line in PRECISION.read_text(encoding="utf-8").splitlines():
        m = _ROW.match(line)
        if m and m.group(1) not in out:
            out[m.group(1)] = {"sampled": m.group(3), "strict": m.group(7), "lenient": m.group(8)}
    return out


def _threshold_key(name: str) -> str:
    return name.lower().replace("_", "-")


def _precision_line(rule: str, table: dict[str, dict[str, str]]) -> str:
    row = table.get(rule)
    if row is None:
        return (
            "Not in the Phase 1 sample (no findings on the corpus, or added later); see "
            "[docs/precision.md](../precision.md) for the Phase 2 addendum."
        )
    return (
        f"Strict **{row['strict']}**, lenient **{row['lenient']}** over {row['sampled']} "
        f"sampled findings on httpx, rich, fastapi, pydantic and black "
        f"([method](../precision.md#method))."
    )


def render_rule(meta: RuleMeta, table: dict[str, dict[str, str]]) -> str:
    doc = RULE_DOCS[meta.id]
    status = "on" if meta.enabled_by_default else "**off** (enable with `[tool.spaghetti.rules]`)"
    lines = [
        f"# `{meta.id}`",
        "",
        f"{meta.summary}.",
        "",
        "| Default severity | Tier | Default |",
        "|---|---|---|",
        f"| {meta.default_severity} | {meta.tier} | {status} |",
        "",
        "## Why it matters",
        "",
        doc.why,
        "",
        "## How to fix it",
        "",
        doc.fix,
        "",
    ]
    if doc.thresholds:
        lines += ["## Thresholds", "", "| Key | Default |", "|---|---|"]
        for name in doc.thresholds:
            value = getattr(_cfg, name)
            key = (
                f"`{_threshold_key(name)}`" if name in threshold_names() else f"`{name}` (CLI flag)"
            )
            lines.append(f"| {key} | {value} |")
        lines.append("")
    lines += ["## Precision", "", _precision_line(meta.id, table), ""]
    lines += ["## Elsewhere", ""]
    if doc.equivalents:
        lines += [f"- {e}" for e in doc.equivalents]
    else:
        lines.append("No equivalent in Pylint, Ruff or SonarQube; spaghetti-specific.")
    lines += [
        "",
        "## Suppress a confirmed non-issue",
        "",
        f"`# spaghetti-ignore[{meta.id}]: reason` on the flagged line or the line above.",
        "",
    ]
    return "\n".join(lines)


def render_index(table: dict[str, dict[str, str]]) -> str:
    lines = [
        "# Rules",
        "",
        f"{len(RULE_CATALOG)} rules in five tiers. Generated by `scripts/gen_rule_docs.py`; "
        "do not edit by hand.",
        "",
        "| Rule | Severity | Tier | Default | Strict precision | Lenient precision |",
        "|---|---|---|---|---|---|",
    ]
    for meta in RULE_CATALOG.values():
        row = table.get(meta.id, {})
        lines.append(
            f"| [`{meta.id}`]({meta.id}.md) | {meta.default_severity} | {meta.tier} | "
            f"{'on' if meta.enabled_by_default else 'off'} | {row.get('strict', '—')} | "
            f"{row.get('lenient', '—')} |"
        )
    lines.append("")
    return "\n".join(lines)


def expected_files() -> dict[Path, str]:
    table = precision_table()
    files = {DOCS / "README.md": render_index(table)}
    for meta in RULE_CATALOG.values():
        files[DOCS / f"{meta.id}.md"] = render_rule(meta, table)
    return files


def main(argv: list[str]) -> int:
    files = expected_files()
    if "--check" in argv:
        stale = [p for p, body in files.items() if not p.exists() or p.read_text() != body]
        extra = [p for p in DOCS.glob("*.md") if p not in files] if DOCS.exists() else []
        for p in stale + extra:
            print(f"stale: {p.relative_to(ROOT)}", file=sys.stderr)
        return 1 if stale or extra else 0
    DOCS.mkdir(parents=True, exist_ok=True)
    for p in DOCS.glob("*.md"):
        if p not in files:
            p.unlink()
    for p, body in files.items():
        p.write_text(body, encoding="utf-8")
    print(f"wrote {len(files)} file(s) to {DOCS.relative_to(ROOT)}")
    return 0


if __name__ == "__main__":
    sys.exit(main(sys.argv[1:]))
